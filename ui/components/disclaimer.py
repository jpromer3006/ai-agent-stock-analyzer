# Compact one-line version (for tight UI spaces / global page footer)
# ---------------------------------------------------------------------------
DISCLAIMER_SHORT: str = (
    "⚠️ For educational and informational purposes only — not investment "
    "advice. The eight peer strategies (stage analysis, momentum, growth, "
    "value, and others) and the bull_prob score are heuristics with known "
    "limitations (model assumptions, data quality, changing market conditions). "
    "Methodologies are referenced for attribution only; no author endorses or "
    "is affiliated with OROS. Does not consider your individual circumstances. "
    "Consult a licensed advisor before investing."
)


# ---------------------------------------------------------------------------
# Streamlit renderer
# ---------------------------------------------------------------------------
def render_disclaimer(compact: bool = False) -> None:
    """
    Render the disclaimer in a Streamlit page.

    Args:
        compact: If True, render the one-line short version in a small caption.
                 If False, render the full markdown disclaimer in a styled
                 container that visually separates it from analytical content.

    Use compact=True for a global page footer (always visible).
    Use compact=False at the bottom of any analysis output (memo, scoreboard).
    """
    if compact:
        # Subtle styled caption — always visible at page bottom
        st.markdown(
            f"""
            <div style="
                margin-top: 2rem;
                padding: 0.75rem 1rem;
                border-top: 1px solid rgba(255,255,255,0.08);
                color: rgba(255,255,255,0.55);
                font-size: 0.78rem;
                line-height: 1.4;
                text-align: center;
            ">
                {DISCLAIMER_SHORT}
            </div>
            """,
            unsafe_allow_html=True,
        )
        return

    # Full disclaimer — wrapped in an expander so it's prominent but collapsible
    with st.expander("⚠️ Important Disclaimer — Read Before Use", expanded=False):
        st.markdown(DISCLAIMER_MARKDOWN)
